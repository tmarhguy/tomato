HEADER = """// AUTO-GENERATED by tools/gen_font_rom.py — do not edit
/*
 * Tomato — 8x8 glyph ROM for the text-mode scanout
 *
 * addr = {{glyph[7:0], row[2:0]}}; data bit 0 is the LEFTMOST pixel of the row,
 * so videoout can index data[col] with col counting left to right.
 *
 * Glyphs 0x20-0x7E: font8x8_basic (public domain). 0x07-0x1F and 0xB0-0xDF:
 * the CP437 arrows, shades and box rule Tomato OS draws its chrome with.
 *
 * SPDX-License-Identifier: CERN-OHL-P-2.0
 */
module font_rom (
    input             clk,
    input      [10:0] addr,
    output reg [7:0]  data
);
    (* rom_style = "block" *) reg [7:0] mem [0:2047];
    integer i;
    initial begin
        for (i = 0; i < 2048; i = i + 1) mem[i] = 8'h00;
"""

FOOTER = """    end

    always @(posedge clk) data <= mem[addr];
endmodule
"""


def main() -> int:
    glyphs = dict(ASCII)
    glyphs.update(EXTRA)

    lines = []
    for code in sorted(glyphs):
        rows = glyphs[code]
        if len(rows) != 8:
            raise SystemExit(f"glyph {code:#04x} has {len(rows)} rows, want 8")
        for row, bits in enumerate(rows):
            if bits:
                lines.append(f"        mem[11'h{(code << 3) | row:03X}] = 8'h{bits:02X};")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(lines) + "\n" + FOOTER)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(glyphs)} glyphs, {len(lines)} non-zero rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
